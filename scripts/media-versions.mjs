/*
 * Writes data/media-versions.ts: one short hash per concept, taken from the
 * contents of every file in public/work/<slug>/.
 *
 *   node scripts/media-versions.mjs
 *
 * Concept media is cached by browsers for a year (next.config.ts), so a
 * recaptured file under the same name would never reach anyone who has seen
 * the old one. The site adds ?v=<hash> to every media URL (data/work.ts):
 * new captures get new URLs, unchanged ones keep their cache. Runs before
 * every build (npm "prebuild") and after every capture.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const workDir = path.join(root, "public", "work");

async function files(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await files(p)));
    else out.push(p);
  }
  return out.sort();
}

const versions = {};
for (const entry of (await readdir(workDir, { withFileTypes: true })).filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const hash = createHash("sha1");
  const dir = path.join(workDir, entry.name);
  for (const file of await files(dir)) {
    hash.update(path.relative(dir, file).replace(/\\/g, "/"));
    hash.update(await readFile(file));
  }
  versions[entry.name] = hash.digest("hex").slice(0, 10);
}

const body = `// Generated by scripts/media-versions.mjs. Do not edit by hand.
export const mediaVersions: Record<string, string> = ${JSON.stringify(versions, null, 2).replace(/"([a-z0-9-]+)":/g, (_, k) => (/^[a-z]\w*$/.test(k) ? `${k}:` : `"${k}":`))};
`;
await writeFile(path.join(root, "data", "media-versions.ts"), body);
console.log("media versions:", Object.entries(versions).map(([k, v]) => `${k} ${v}`).join(", "));
